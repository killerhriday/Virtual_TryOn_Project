// ─── API: Set Tunnel URL & Send Handshake ───
app.post('/api/set-tunnel', async (req, res) => {
  const { tunnelUrl: url } = req.body;
  if (!url) {
    return res.status(400).json({ success: false, error: 'No tunnel URL provided' });
  }
  tunnelUrl = url.replace(/\/$/, ''); // Remove trailing slash
  console.log(`\n✅ Tunnel URL configured: ${tunnelUrl}`);
  console.log(`   API Endpoint: ${tunnelUrl}/process`);
  
  if (!myWebhookUrl) {
    console.warn(`⚠️ Warning: My localtunnel isn't ready yet, registration handshake may fail.`);
  } else {
    try {
      console.log(`🤝 Sending registration handshake to AI Server...`);
      await axios.post(`${tunnelUrl}/register`, {
        client_webhook_url: `${myWebhookUrl}/webhook`
      }, {
        headers: {
          'Bypass-Tunnel-Reminder': 'true'
        }
      });
      console.log(`✅ Handshake successful! AI server knows our webhook.`);
    } catch (err) {
      console.error(`⚠️ Registration handshake failed:`, err.response?.data || err.message);
      // We don't fail the frontend request if handshake fails, just log it.
    }
  }

  res.json({ success: true, tunnelUrl });
});

// ─── API: Check if tunnel is configured ───
app.get('/api/tunnel-status', (req, res) => {
  res.json({ configured: !!tunnelUrl, tunnelUrl });
});

// Configure Multer for file uploads
const storage = multer.diskStorage({
  destination: (req, file, cb) => {
    cb(null, UPLOADS_DIR);
  },
  filename: (req, file, cb) => {
    // Generate a random name for the client photo
    const randomHex = crypto.randomBytes(8).toString('hex');
    const ext = path.extname(file.originalname);
    cb(null, `client_${randomHex}${ext}`);
  }
});
const upload = multer({ storage });

// ─── API: Generate Image (Trigger Job) ───
app.post('/api/generate', upload.single('clientImage'), async (req, res) => {
  try {
    if (!tunnelUrl) {
      return res.status(400).json({ 
        success: false, 
        error: 'AI server not configured! Go to http://localhost:3001/config first.' 
      });
    }

    if (!req.file) {
      return res.status(400).json({ error: 'No client image uploaded' });
    }

    const clientImageName = req.file.filename;
    const clientImagePath = req.file.path;
    const clothingItemId = req.body.clothingId || 'unknown'; 

    const friendLaptopUrl = `${tunnelUrl}/process`;

    console.log(`[NETWORK EVENT] Received Generate Request`);
    console.log(`1. Client Image saved as: ${clientImageName}`);
    console.log(`2. Target Clothing ID: ${clothingItemId}`);
    console.log(`[NETWORK EVENT] Transmitting job to AI Server...`);

    // Prepare the form data to send to the friend's laptop
    const fileBuffer = fs.readFileSync(clientImagePath);
    const formData = new FormData();
    formData.append('clientImage', fileBuffer, { 
      filename: clientImageName,
      contentType: 'image/jpeg'
    });
    
    // Grab the corresponding clothing picture from the frontend assets
    const filenameMap = {
      '1': '001.jpeg',
      '2': '002.png',
      '3': '003.png',
      '4': '004.png'
    };
    const clothingFileName = filenameMap[clothingItemId] || '001.jpeg';
    const clothingImagePath = path.join(__dirname, '../frontend/src/assets', clothingFileName);
    
    if (fs.existsSync(clothingImagePath)) {
      const clothingBuffer = fs.readFileSync(clothingImagePath);
      formData.append('clothingImage', clothingBuffer, {
        filename: clothingFileName,
        contentType: clothingFileName.endsWith('.png') ? 'image/png' : 'image/jpeg'
      });
    }

    formData.append('clothingId', clothingItemId);

    // Reset the global state to processing
    generationState = { status: 'processing', imageUrl: null, error: null };

    try {
      // Send the POST request to the friend's laptop via Localtunnel
      const aiResponse = await axios.post(friendLaptopUrl, formData, {
        headers: {
          ...formData.getHeaders(),
          'Content-Length': formData.getLengthSync(),
          'Bypass-Tunnel-Reminder': 'true'
        },
        proxy: false
      });

      console.log(`[NETWORK EVENT] AI Server acknowledged job! Status:`, aiResponse.data);
      
      res.json({
        success: true,
        message: 'Job started successfully. Polling for results...',
      });

    } catch (networkError) {
      const serverFeedback = networkError.response?.data || networkError.message;
      console.error(`[NETWORK ERROR] AI Server rejected request:`, serverFeedback);
      generationState = { status: 'error', imageUrl: null, error: serverFeedback };
      
      res.json({
        success: false,
        error: 'The AI server rejected the request.',
        details: serverFeedback
      });
    }

  } catch (error) {
    console.error('Server error:', error);
    res.status(500).json({ error: 'Internal server error' });
  }
});

// ─── API: Webhook Receiver (From AI Server) ───
app.post('/webhook', (req, res) => {
  console.log(`[WEBHOOK EVENT] Received payload from AI Server!`);
  
  // 1. Respond instantly so the tunnel doesn't time out
  res.status(200).json({ success: true });

  // 2. Process the image asynchronously in the background
  setTimeout(() => {
    try {
      const error = req.body.error;
      const generatedImageUrl = req.body.generatedImageUrl;
      
      if (error) {
        console.error(`[WEBHOOK EVENT] AI Server reported an error:`, error);
        generationState = { status: 'error', imageUrl: null, error };
        return;
      }

      if (!generatedImageUrl) {
        console.error(`[WEBHOOK EVENT] No image URL found in webhook payload.`);
        generationState = { status: 'error', imageUrl: null, error: 'Missing image URL' };
        return;
      }

      console.log(`[WEBHOOK EVENT] Received image URL: ${generatedImageUrl}`);
      
      // Update global state so frontend polling picks it up
      // We route the image through our proxy to inject the Bypass-Tunnel-Reminder header
      const proxyUrl = `http://localhost:3001/api/proxy-image?url=${encodeURIComponent(generatedImageUrl)}`;
      generationState = { 
        status: 'completed', 
        imageUrl: proxyUrl,
        error: null 
      };
    } catch (err) {
      console.error(`[WEBHOOK EVENT] Error processing webhook:`, err);
      generationState = { status: 'error', imageUrl: null, error: 'Failed to process webhook image' };
    }
  }, 0);
});

// ─── API: Image Proxy ───
app.get('/api/proxy-image', async (req, res) => {
  const targetUrl = req.query.url;
  if (!targetUrl) {
    return res.status(400).send('No URL provided');
  }

  try {
    const response = await axios({
      method: 'GET',
      url: targetUrl,
      responseType: 'stream',
      headers: {
        'Bypass-Tunnel-Reminder': 'true'
      }
    });

    res.setHeader('Content-Type', response.headers['content-type'] || 'image/jpeg');
    response.data.pipe(res);
  } catch (error) {
    console.error(`[PROXY ERROR] Failed to fetch image from ${targetUrl}:`, error.message);
    res.status(500).send('Error proxying image');
  }
});

// ─── API: Status Polling ───
app.get('/api/status', (req, res) => {
  res.json(generationState);
});

