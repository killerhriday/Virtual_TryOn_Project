const PORT = 3001;
let currentTunnel = null;

async function startTunnel() {
  try {
    if (currentTunnel) {
      currentTunnel.removeAllListeners(); // Prevent duplicate setTimeout loops
      currentTunnel.close();
    }
    
    currentTunnel = await localtunnel({ port: PORT, local_host: '127.0.0.1' });
    myWebhookUrl = currentTunnel.url;
    console.log(`📡 Mac's Webhook URL established at: ${myWebhookUrl}`);
    console.log(`🔗 Open http://127.0.0.1:${PORT}/config to connect to AI server\n`);
    
    // If the frontend has already set the friend's tunnel URL, instantly re-register!
    if (tunnelUrl) {
      console.log(`🔄 Tunnel reconnected! Re-registering handshake with AI Server...`);
      try {
        await axios.post(`${tunnelUrl}/register`, {
          client_webhook_url: `${myWebhookUrl}/webhook`
        }, { headers: { 'Bypass-Tunnel-Reminder': 'true' } });
        console.log(`✅ Re-registration successful!`);
      } catch (err) {
        console.error(`⚠️ Re-registration handshake failed:`, err.message);
      }
    }

    currentTunnel.on('close', () => {
      console.log('⚠️ Tunnel closed! Attempting to reconnect in 3 seconds...');
      setTimeout(startTunnel, 3000);
    });

    currentTunnel.on('error', (err) => {
      console.error('⚠️ Tunnel error:', err);
      currentTunnel.close(); // Triggers the 'close' event to restart it
    });

  } catch (err) {
    console.error('Failed to create localtunnel, retrying in 3 seconds...', err);
    setTimeout(startTunnel, 3000);
  }
}

app.listen(PORT, '127.0.0.1', () => {
  console.log(`\n🚀 Backend Hub running on http://127.0.0.1:${PORT}`);
  startTunnel();
});
